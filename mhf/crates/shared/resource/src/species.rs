//! Display labels only, never a species registration or validity list.
// Chinese names: https://w.atwiki.jp/mhfotw/pages/22.html
// and https://monsterhunterwiki.org/wiki/Uruki

/// Display name for any byte-sized species ID, independent of resource counts.
pub fn name(id: u8) -> std::borrow::Cow<'static, str> {
    match NAMES.get(usize::from(id)) {
        Some(name) => std::borrow::Cow::Borrowed(name),
        None => std::borrow::Cow::Owned(format!("em{id:03}")),
    }
}

